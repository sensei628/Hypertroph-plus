#!/usr/bin/env node
// Importer for the public-domain "Free Exercise DB" (yuhonas/free-exercise-db),
// released under The Unlicense. Produces db/exercises.sql, which is committed
// and applied as a schema migration (so existing user DBs get it too).
//
// Usage:
//   node tools/import/import-exercises.mjs --in tools/import/.cache/exercises.json \
//     --out db/exercises.sql
//
// The source JSON is NOT committed (see .gitignore: tools/import/.cache/).
// Only the derived SQL is committed; the dataset is public domain.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..', '..');

function arg(name, def) {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 && process.argv[i + 1] && !process.argv[i + 1].startsWith('--') ? process.argv[i + 1] : def;
}

const inFile = path.resolve(repoRoot, arg('in', 'tools/import/.cache/exercises.json'));
const outFile = path.resolve(repoRoot, arg('out', 'db/exercises.sql'));
if (!fs.existsSync(inFile)) {
  console.error(`Input not found: ${inFile}\nRun tools/import/download-exercises.ps1 first.`);
  process.exit(2);
}

const SOURCE_ID = 's_exdb';
const IMPORT_TS = 1730000000000;

// Free Exercise DB muscle vocabulary -> app muscle ids. Muscles with no app
// equivalent are added as new app muscles (see NEW_MUSCLES) rather than being
// misattributed to a different muscle.
const MUSCLE_MAP = {
  abdominals: 'core',
  quadriceps: 'quads',
  'middle back': 'back',
  'lower back': 'erectors',
  lats: 'lats',
  traps: 'traps',
  shoulders: 'shoulders',
  calves: 'calves',
  forearms: 'forearms',
  neck: 'neck',
  adductors: 'adductors',
  abductors: 'abductors',
  chest: 'chest',
  biceps: 'biceps',
  triceps: 'triceps',
  hamstrings: 'hamstrings',
  glutes: 'glutes',
};

const NEW_MUSCLES = [
  ['shoulders', 'Shoulders', 'upper'],
  ['traps', 'Traps', 'upper'],
  ['forearms', 'Forearms', 'upper'],
  ['neck', 'Neck', 'upper'],
  ['calves', 'Calves', 'lower'],
  ['adductors', 'Adductors', 'lower'],
  ['abductors', 'Abductors', 'lower'],
];

// Free Exercise DB equipment -> app equipment ids. null = no equipment recorded.
const EQUIPMENT_MAP = {
  'body only': 'bodyweight',
  'e-z curl bar': 'ez_bar',
  'medicine ball': 'medicine_ball',
  'exercise ball': 'exercise_ball',
  'foam roll': null,
  other: null,
  kettlebells: 'kettlebell',
  bands: 'band',
  barbell: 'barbell',
  dumbbell: 'dumbbell',
  cable: 'cable',
  machine: 'machine',
};

const NEW_EQUIPMENT = [
  ['ez_bar', 'E-Z curl bar'],
  ['medicine_ball', 'Medicine ball'],
  ['exercise_ball', 'Exercise ball'],
];

// Free Exercise DB `category` -> app exercise_categories. This is the *real*
// catalogue field (strength/powerlifting/...), mapped onto our coarser axes.
const CATEGORY_MAP = {
  strength: 'resistance',
  powerlifting: 'resistance',
  strongman: 'resistance',
  'olympic weightlifting': 'resistance',
  cardio: 'cardio',
  stretching: 'stretching',
  plyometrics: 'mobility',
};

const UNILATERAL = /single|one[- ](arm|leg)/i;

const q = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const normalizeKey = (s) =>
  String(s)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();

const data = JSON.parse(fs.readFileSync(inFile, 'utf8'));
if (!Array.isArray(data)) {
  console.error('Expected a JSON array of exercises.');
  process.exit(2);
}

const lines = [];
lines.push('-- AUTO-GENERATED by tools/import/import-exercises.mjs — do not edit by hand.');
lines.push('-- Source: Free Exercise DB (yuhonas/free-exercise-db), The Unlicense (public domain).');
lines.push(`-- Exercises: ${data.length}`);
lines.push('');

lines.push(
  `INSERT OR IGNORE INTO sources (id, name, license, license_url, attribution, redistribution, pack_version, retrieved_at)\n` +
    `  VALUES (${q(SOURCE_ID)}, ${q('Free Exercise DB')}, ${q('Unlicense')}, ${q('https://github.com/yuhonas/free-exercise-db/blob/master/LICENSE')}, ` +
    `${q('Exercise data from Free Exercise DB (unlicense.org, public domain).')}, ${q('allowed')}, ${q('free-exercise-db')}, ${IMPORT_TS});`,
);
lines.push('');

for (const [id, name, region] of NEW_MUSCLES) {
  lines.push(`INSERT OR IGNORE INTO muscles (id, name, region, parent_id) VALUES (${q(id)}, ${q(name)}, ${q(region)}, NULL);`);
}
lines.push('');
for (const [id, name] of NEW_EQUIPMENT) {
  lines.push(`INSERT OR IGNORE INTO equipment (id, name) VALUES (${q(id)}, ${q(name)});`);
}
lines.push('');

let nEx = 0;
let nMuscleRows = 0;
let nEquipRows = 0;
let nCats = 0;
const seenId = new Set();
const byCategory = new Map(); // app category id -> [exercise ids]

for (const ex of data) {
  if (!ex || !ex.id || !ex.name) continue;
  const id = `e_${String(ex.id).replace(/[^a-zA-Z0-9]+/g, '_')}`;
  if (seenId.has(id)) continue;
  seenId.add(id);
  const unilateral = UNILATERAL.test(ex.name) ? 1 : 0;

  lines.push(
    `INSERT OR IGNORE INTO exercises (id, canonical_name, search_key, source_id, source_record_id, unilateral, is_custom, is_deleted, variation_group, created_at, updated_at)\n` +
      `  VALUES (${q(id)}, ${q(ex.name)}, ${q(normalizeKey(ex.name))}, ${q(SOURCE_ID)}, ${q(ex.id)}, ${unilateral}, 0, 0, NULL, ${IMPORT_TS}, ${IMPORT_TS});`,
  );
  nEx++;

  for (const [role, list] of [
    ['primary', ex.primaryMuscles],
    ['secondary', ex.secondaryMuscles],
  ]) {
    for (const raw of list || []) {
      const muscleId = MUSCLE_MAP[raw];
      if (!muscleId) continue;
      lines.push(
        `INSERT OR IGNORE INTO exercise_muscles (exercise_id, muscle_id, role) VALUES (${q(id)}, ${q(muscleId)}, ${q(role)});`,
      );
      nMuscleRows++;
    }
  }

  const equip = ex.equipment ? EQUIPMENT_MAP[ex.equipment] : null;
  if (equip) {
    lines.push(
      `INSERT OR IGNORE INTO exercise_equipment (exercise_id, equipment_id) VALUES (${q(id)}, ${q(equip)});`,
    );
    nEquipRows++;
  }

  // Preserve the source's real category field (mapped onto app categories),
  // emitted as a separate committed data file applied by a later migration.
  const cat = CATEGORY_MAP[ex.category] ?? 'other';
  if (!byCategory.has(cat)) byCategory.set(cat, []);
  byCategory.get(cat).push(id);
  nCats++;
}

lines.push('');
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, lines.join('\n'));

// Companion data file: real (source-verifiable) exercise->category assignment,
// emitted so a later migration can backfill existing databases idempotently
// (UPDATE-by-id is safe on both fresh and populated exercises tables).
const catOut = path.resolve(repoRoot, arg('cats', 'db/exercise_categories.sql'));
const catLines = [
  '-- AUTO-GENERATED by tools/import/import-exercises.mjs — do not edit by hand.',
  '-- Exercise category assignments carried verbatim from the Free Exercise DB',
  '-- `category` field, mapped onto app exercise categories. Applied by migration v6.',
  '',
  `UPDATE exercises SET category_id = NULL WHERE category_id IS NOT NULL;`,
  '',
];
for (const [cat, ids] of byCategory) {
  catLines.push(`UPDATE exercises SET category_id = ${q(cat)} WHERE id IN (${ids.map(q).join(', ')});\n`);
}
fs.writeFileSync(catOut, catLines.join('\n'));

console.log('--- exercise import summary ---');
console.log(`exercises       : ${nEx}`);
console.log(`muscle links    : ${nMuscleRows}`);
console.log(`equipment links : ${nEquipRows}`);
console.log(`category links  : ${nCats}`);
console.log(`sql file        : ${path.relative(repoRoot, outFile)} (${(fs.statSync(outFile).size / 1024).toFixed(0)} KB)`);
console.log(`categories file : ${path.relative(repoRoot, catOut)} (${(fs.statSync(catOut).size / 1024).toFixed(1)} KB)`);
