function applyMigrations(db: DB): boolean {
  let current = 0;
  try {
    const stmt = db.prepare('SELECT MAX(version) AS v FROM schema_migrations');
    if (stmt.step()) {
      const row = stmt.getAsObject() as { v: number | null };
      current = row.v ?? 0;
    }
    stmt.free();
  } catch {
    return false;
  }
  if ((current ?? 0) >= Math.max(...MIGRATIONS.map((m) => m.version))) return false;
  // Some migrations rebuild tables (dropping parents with live FKs). Constraint
  // enforcement is re-checked afterwards via foreign_key_check.
  const fkOn = db.exec('PRAGMA foreign_keys')[0]?.values[0]?.[0] === 1;
  if (fkOn) db.run('PRAGMA foreign_keys = OFF');
  let changed = false;
  try {
    for (const m of MIGRATIONS) {
      if (m.version <= current) continue;
      db.run('BEGIN');
      try {
        db.run(m.sql);
        db.run('INSERT INTO schema_migrations (version, applied_at, checksum) VALUES (?, ?, ?)', [
          m.version,
          Date.now(),
          `compliance-v${m.version}`,
        ]);
        db.run('COMMIT');
        changed = true;
        current = m.version;
      } catch (e) {
        db.run('ROLLBACK');
        throw e;
      }
    }
  } finally {
    if (fkOn) {
      db.run('PRAGMA foreign_keys = ON');
      const violations = db.exec('PRAGMA foreign_key_check');
      if (violations.length) throw new Error('Migration left dangling foreign keys');
    }
  }
  return changed;
}

let sqlStatic: SqlJsStatic | null = null;

/** Shared sql.js runtime (WASM). Used by both the user DB and the reference DB. */
export async function getSqlStatic(): Promise<SqlJsStatic> {
  if (!sqlStatic) {
    sqlStatic = await initSqlJs({ locateFile: () => wasmUrl });
  }
  return sqlStatic;
}

/**
 * Load the SQLite database. Persistence is delegated to the platform storage
 * adapter (see ./storage): a real on-device file under Capacitor, localStorage
 * on the web. The schema, seed and migration logic are identical to the web
 * build.
 */
export async function loadDatabase(): Promise<DB> {
  const SQL = await getSqlStatic();

  const stored = await storage.load();
  let db: DB;
  let fresh = false;

  if (stored) {
    db = new SQL.Database(stored);
  } else {
    db = new SQL.Database();
    db.run(schemaSql);
    db.run(seedSql);
    fresh = true;
  }

  db.run('PRAGMA foreign_keys = ON;');
  const migrated = applyMigrations(db);
  if (fresh || migrated) persist(db);
  return db;
}

/** Queue the current database image to platform storage. */
export function persist(db: DB): void {
  storage.save(db.export());
}

/** Remove the persisted image and flush any pending native write. */
export async function resetDatabase(): Promise<void> {
  await storage.reset();
}

/** Wait for any queued/in-flight native persistence write to complete. */
export function flushPersistence(): Promise<void> {
  return storage.flush();
}

export function exportDatabaseBytes(db: DB): Uint8Array {
  return db.export();
}
